import streamlit as st

from langchain_core.messages import HumanMessage

from graph import workflow


st.set_page_config(
    page_title="EV Assistant",
    page_icon="⚡",
    layout="centered"
)


st.title("⚡ EV Charging Analytics AI Assistant\nAsk questions about EV Charging Stations for analysis", text_alignment='center')



# --------------------------------------------------
# Session State
# --------------------------------------------------

if "messages" not in st.session_state:
    st.session_state.messages = []

CONFIG = {'configurable':{'thread_id':'1'}}

# --------------------------------------------------
# Display previous messages
# --------------------------------------------------

for message in st.session_state.messages:

    if message["role"] == "user":

        with st.chat_message("user"):
            st.write(message["content"])

    else:

        with st.chat_message("assistant"):
            st.write(message["content"])


# --------------------------------------------------
# User Input
# --------------------------------------------------

user_input = st.chat_input(
    "Ask questions like, Give me station wise total revenue...."
)


if user_input:

    # Display user message

    with st.chat_message("user"):
        st.write(user_input)

    st.session_state.messages.append(
        {
            "role": "user",
            "content": user_input
        }
    )


    # --------------------------------------------------
    # Run LangGraph
    # --------------------------------------------------

    with st.chat_message("assistant"):

        result = workflow.stream(
            {
                "messages":HumanMessage(content=user_input),
                "sql_retry_count":0
            },
            config=CONFIG,
            stream_mode="messages"
        )

        def generate_response():

            for message_chunk, metadata in result:

                # Only stream messages generated by chatbot node
                if metadata.get("langgraph_node") == "chat_node":

                    if message_chunk.content:
                        yield message_chunk.content


        ai_message = st.write_stream(generate_response())


    st.session_state.messages.append(
        {
            "role": "assistant",
            "content": ai_message
        }
    )
